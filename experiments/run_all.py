"""Run every experiment and write results/RESULTS.md from what came back.

The document is generated, never edited, so it cannot drift from the code that
produced it.  Each run records the build it ran against -- S4.__version__ and
the install's BUILD-INFO.txt -- because a number without a build is not a
result.

    python run_all.py                 # writes results/RESULTS.md
    python run_all.py exp01           # one experiment, to stdout
"""
import argparse
import importlib
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENTS = ["exp01_plane_interface", "exp02_ellipse_identity",
               "exp03_geometry_gate", "exp04_convergence"]


def table(headers, rows):
    widths = [max(len(h), *(len(r[i]) for r in rows)) if rows else len(h)
              for i, h in enumerate(headers)]
    out = ["| " + " | ".join(h.ljust(w) for h, w in zip(headers, widths)) + " |",
           "|" + "|".join("-" * (w + 2) for w in widths) + "|"]
    for r in rows:
        out.append("| " + " | ".join(c.ljust(w) for c, w in zip(r, widths)) + " |")
    return "\n".join(out)


def build_line():
    import S4
    # The build id identifies the source; the absolute path of the extension
    # says only where this machine keeps it, so it is left out.
    line = "S4 %s (%s)" % (S4.__version__, os.path.basename(S4.__file__))
    info = os.path.join(os.path.dirname(S4.__file__), "BUILD-INFO.txt")
    if os.path.exists(info):
        with open(info) as f:
            for row in f:
                if row.startswith(("flavour", "compiler", "host")):
                    line += "\n" + row.rstrip()
    return line


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("only", nargs="?", help="run one experiment by prefix")
    args = ap.parse_args()
    sys.path.insert(0, HERE)

    chosen = [m for m in EXPERIMENTS
              if not args.only or m.startswith(args.only)]
    if not chosen:
        print("no experiment matches %r" % args.only)
        return 1

    parts, failed = [], 0
    for name in chosen:
        mod = importlib.import_module(name)
        t0 = time.perf_counter()
        r = mod.run()
        secs = time.perf_counter() - t0
        ok = r.get("pass", True)
        failed += 0 if ok else 1
        parts.append("## %s\n\n%s\n\n%s\n" % (
            mod.NAME, (mod.__doc__ or "").strip(),
            table(r["headers"], r["rows"])))
        if "extra" in r:
            e = r["extra"]
            parts.append("%s\n\n%s\n" % (e["caption"], table(e["headers"], e["rows"])))
        parts.append("**%s** -- %s, %.1fs\n" % (
            "as expected" if ok else "NOT as expected", r["summary"], secs))
        print("  %-34s %s  %s" % (name, "ok " if ok else "FAIL", r["summary"]))

    if args.only:
        print("\n" + "\n".join(parts))
        return 1 if failed else 0

    out = os.path.join(HERE, "results", "RESULTS.md")
    with open(out, "w") as f:
        f.write("# Experiment results\n\n"
                "Generated by `run_all.py`; do not edit. Every number here was\n"
                "produced by the run that wrote the file.\n\n```\n%s\n```\n\n---\n\n"
                % build_line())
        f.write("\n---\n\n".join(parts))
    print("\nwrote %s" % out)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
